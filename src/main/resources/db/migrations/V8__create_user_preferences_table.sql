CREATE TABLE user_preferences
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id        BIGINT                                  NOT NULL,
    not_in_college BOOLEAN                                 NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at     TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_user_preferences PRIMARY KEY (id),
    CONSTRAINT uc_user_preferences_user_id UNIQUE (user_id),
    CONSTRAINT fk_user_preferences_on_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_preferences_selected_types
(
    user_preferences_id BIGINT       NOT NULL,
    type                VARCHAR(255) NOT NULL,
    CONSTRAINT fk_user_preferences_selected_types_on_pref FOREIGN KEY (user_preferences_id) REFERENCES user_preferences (id) ON DELETE CASCADE
);

CREATE TABLE user_preferences_institutions
(
    user_preferences_id BIGINT       NOT NULL,
    institution         VARCHAR(255) NOT NULL,
    CONSTRAINT fk_user_preferences_institutions_on_pref FOREIGN KEY (user_preferences_id) REFERENCES user_preferences (id) ON DELETE CASCADE
);

CREATE TABLE user_preferences_target_courses
(
    user_preferences_id    BIGINT       NOT NULL,
    target_course_audience VARCHAR(255) NOT NULL,
    CONSTRAINT fk_user_preferences_target_courses_on_pref FOREIGN KEY (user_preferences_id) REFERENCES user_preferences (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_preferences_user_id ON user_preferences (user_id);
